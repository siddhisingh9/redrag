"""Reports: the full HTML report of the selected scan, as `redrag report` writes it.

The dashboard's other pages are built for exploring; the report is the complete
write-up (every table, the judge-agreement section, which harmless questions were
blocked) in one self-contained file you can download and share.
"""

from __future__ import annotations

import streamlit as st

from dashboard import common
from redrag.eval.html_report import HTML_REPORT_FILE, render_html

loaded = common.current()
if loaded is None:
    st.stop()
info, run = loaded


@st.cache_data(show_spinner="Building the report...", max_entries=8)
def _render(run_id: str, modified: float, agreement: dict | None) -> str:
    # `run_id` and `modified` are only cache keys; the run itself comes from common.load.
    return render_html(run.results, run.info, agreement, run.benign)


saved = info.path / HTML_REPORT_FILE
if saved.exists():
    page = saved.read_text(encoding="utf-8")
else:  # e.g. an interrupted scan that never wrote its report
    page = _render(info.run_id, (info.path / "results.jsonl").stat().st_mtime, common.agreement())

st.title("Report")
left, right = st.columns([3, 1], vertical_alignment="center")
left.caption(f"The full report for **{info.label}**: every table and chart in one file.")
right.download_button(
    "Download HTML",
    page,
    file_name=f"redrag-report-{info.run_id}.html",
    mime="text/html",
    icon=":material/download:",
    width="stretch",
)
# The report is generated by RedRAG and escapes all model output, so it is safe to embed.
st.iframe(page, height="content")
